#!/usr/bin/env node
// Writes plugins/ow-tools/SECURITY-MANIFEST.md: every shipped file with its
// SHA-256, the programs ow-tools runs, its network use and the files it
// writes, so an administrator can review the add-on in one sitting (ow-tools
// design §7; audit A:142, A:3282). `--check` fails on drift; a test runs it.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const PLUGIN = join(ROOT, "plugins", "ow-tools");
const OUT = join(PLUGIN, "SECURITY-MANIFEST.md");

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === ".venv" || e.name === "__pycache__" || e.name === "node_modules") continue;
      yield* walk(p);
    } else if (e.isFile() && p !== OUT && e.name !== ".DS_Store") yield p;
  }
}

export function render() {
  const { version } = JSON.parse(readFileSync(join(PLUGIN, ".claude-plugin", "plugin.json"), "utf8"));
  const rows = [...walk(PLUGIN)].map((p) => {
    const rel = relative(PLUGIN, p).split(sep).join("/");
    const hash = createHash("sha256").update(readFileSync(p)).digest("hex");
    return `| \`${rel}\` | \`${hash}\` |`;
  });
  return `# ow-tools ${version} — security manifest

Generated by \`scripts/gen-ow-tools-manifest.mjs\`. Do not edit by hand.

## Runs code

**Yes.** \`bin/ow-tools\` (POSIX sh) starts \`lib/cli.mjs\` (Node.js, built-in modules only; no npm dependencies, so Claude Code runs no npm install). \`python/diarize.py\` runs in a private Python 3.12 environment built by uv from the committed \`python/uv.lock\`. The SessionStart hook runs \`bin/ow-tools hook session-start\`, which reads \`opchain-work/STATUS.md\` and writes nothing.

## Programs it runs

| Program | When | Why |
|---|---|---|
| \`ffmpeg\` | transcribe | Normalise the recording to 16 kHz mono WAV in a private temp folder |
| \`whisper-cli\` | transcribe | Speech to text with timestamps (local model file) |
| \`uv run --frozen\` → \`python diarize.py\` | transcribe | Speaker separation, with \`HF_HUB_OFFLINE=1\`, \`UV_OFFLINE=1\` and no token in its environment |
| \`pandoc\` | export | Markdown to Typst and to Word |
| \`typst compile --pdf-standard ua-1\` | export | Tagged PDF; \`--root\` is the private temp folder |
| \`zip\`, \`unzip\` | export | Add brand styles, header and footer to the Word file |
| \`git rev-parse\`, \`git check-ignore\` | transcribe, hook | Is a path inside a repository, and is it ignored |
| \`security find-generic-password\` (no \`-w\`) | doctor (macOS) | Is a Hugging Face token stored; the value is never read |
| \`typst fonts\`; each tool's \`--version\` | doctor, export | Versions and installed fonts |

It never runs \`brew\`, \`apt\`, \`sudo\`, \`uv sync\`, \`curl\` or a model download. \`ow-tools doctor\` prints those for the user to run.

## Network

**None at run time.** The user-run setup steps that \`ow-tools doctor\` prints reach: Homebrew (packages), huggingface.co (the Whisper model; the pyannote model with the user's token), PyPI and python-build-standalone via uv (the Python environment).

## Files it writes

| What | Where |
|---|---|
| \`transcript.json\`, \`transcript.md\` | The workstream folder the user names (refused unless git-ignored when inside a repository) |
| \`<name>.pdf\`, \`<name>.docx\` | \`export/\` beside the Markdown, or \`--out\` |
| Temporary audio, model output, Word parts | A private (0700) temp folder, removed when the run ends |

## Files

| File | SHA-256 |
|---|---|
${rows.join("\n")}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      /* missing counts as drift */
    }
    if (current !== text) {
      console.error("✗ plugins/ow-tools/SECURITY-MANIFEST.md is out of date; run: node scripts/gen-ow-tools-manifest.mjs");
      process.exit(1);
    }
    console.log("✓ ow-tools security manifest is current");
  } else {
    writeFileSync(OUT, text);
    console.log("wrote plugins/ow-tools/SECURITY-MANIFEST.md");
  }
}
