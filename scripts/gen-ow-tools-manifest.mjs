#!/usr/bin/env node
// Writes plugins/ow-tools/SECURITY-MANIFEST.md: every shipped file with its
// SHA-256, the programs ow-tools runs, its network use and the files it
// writes, so an administrator can review the add-on in one sitting (ow-tools
// design §7; audit A:142, A:3282). `--check` fails on drift; a test runs it.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const PLUGIN = join(ROOT, "plugins", "ow-tools");
const OUT = join(PLUGIN, "SECURITY-MANIFEST.md");

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === ".venv" || e.name === "__pycache__" || e.name === "node_modules") continue;
      yield* walk(p);
    } else if (e.isFile() && p !== OUT && e.name !== ".DS_Store") yield p;
  }
}

export function render() {
  const { version } = JSON.parse(readFileSync(join(PLUGIN, ".claude-plugin", "plugin.json"), "utf8"));
  const rows = [...walk(PLUGIN)].map((p) => {
    const rel = relative(PLUGIN, p).split(sep).join("/");
    const hash = createHash("sha256").update(readFileSync(p)).digest("hex");
    return `| \`${rel}\` | \`${hash}\` |`;
  });
  return `# ow-tools ${version} — security manifest

Generated by \`scripts/gen-ow-tools-manifest.mjs\`. Do not edit by hand.

## Runs code

**Yes.** \`bin/ow-tools\` (POSIX sh) starts \`lib/cli.mjs\` (Node.js, built-in modules only; no npm dependencies, so Claude Code runs no npm install). \`python/diarize.py\` runs in a private Python 3.12 environment built by uv from the committed \`python/uv.lock\`. The SessionStart hook runs \`bin/ow-tools hook session-start\`, which reads \`opchain-work/STATUS.md\`, checks PATH and a few files for readiness (it never starts a browser or Python), and writes nothing.

## Programs it runs

| Program | When | Why |
|---|---|---|
| \`ffmpeg -protocol_whitelist file\` | transcribe | Normalise the recording to 16 kHz mono WAV in a private temp folder; only the local file protocol is allowed |
| \`whisper-cli\` | transcribe | Speech to text with timestamps (local model file) |
| \`uv run --frozen --no-sync\` → \`python diarize.py\` | transcribe | Speaker separation, with \`HF_HUB_OFFLINE=1\`, \`UV_OFFLINE=1\` and no token in its environment |
| \`pandoc\` | export | Markdown to Typst, to Word and (1.1.0) to PowerPoint (\`-t pptx\`, and \`--print-default-data-file reference.pptx\` for the per-run reference deck) |
| \`typst compile --pdf-standard ua-1\` | export | Tagged PDF; \`--root\` is the private temp folder |
| \`zip\`, \`unzip\` | export | Add brand styles, header and footer to the Word file; brand the reference deck and the PowerPoint file (1.1.0) |
| Chrome or Chromium (1.1.0): \`--remote-debugging-pipe\`, never a debugging port | capture | Screenshots of the test environment the plan names, on the profile in \`$OW_TOOLS_HOME/capture/<workstream>/\`; found on PATH or at the standard paths, never downloaded. Its cookie key is in the user's keychain (no mock keychain) |
| \`pip-audit -r <file> --disable-pip --no-deps --vulnerability-service osv --format json --progress-spinner off\` (1.1.0, optional) | health | Python advisories for a fully pinned requirements file, in its no-install mode only, from OSV, with \`NETRC=/dev/null\` and \`PIP_CONFIG_FILE=/dev/null\` |
| \`git rev-parse\`, \`git check-ignore\` | transcribe, speakers, capture, hook | Is a path inside a repository, and is it ignored |
| \`security find-generic-password\` (no \`-w\`) | doctor (macOS) | Is a Hugging Face token stored; the value is never read |
| \`typst fonts\`; each tool's \`--version\` | doctor, export, transcribe | Versions and installed fonts (the browser's version is never asked: that would start it) |

It never runs \`brew\`, \`apt\`, \`sudo\`, \`uv sync\`, \`curl\`, \`npm\`, \`pip install\` or a model or browser download; \`ow-tools doctor\` prints those for the user to run. Transcription's \`uv run --no-sync\` uses the environment the user built and never installs into it.

## Network

By verb. Every other verb, \`ow-tools doctor\` and the SessionStart hook open no socket.

| Verb | Reaches | What it sends |
|---|---|---|
| \`capture\` (1.1.0) | The system resolver, once per host name in \`allowed_origins\`, before launch (a loopback or link-local answer refuses the plan). Then only those origins (https; never loopback in any spelling, never link-local), through the browser, at the addresses ow-tools checked. Every other request the page makes is failed; the browser resolves no other name (a host-resolver map: each allowed name to its checked address, everything else not found), and its own background traffic is turned down by flags. Service-worker fetches and WebSockets are not seen by the request guard (the host map still applies) | Each allowed host name (DNS); what the browser sends to the test environment, including the plan's test data in \`fill\` steps; never a credential typed by ow-tools |
| \`health\` (1.1.0) | \`api.osv.dev\`; \`registry.npmjs.org\`; \`data.iana.org\` (the RDAP list, at most once in 30 days); the RDAP server that list names over https for each listed domain; the hosts and URLs \`health.yaml\` lists. pip-audit, when it runs, makes its own requests to \`api.osv.dev\` (\`--vulnerability-service osv\`), outside the address rules below | The name and version of each public-registry package with a plain semver version (POST to OSV); each such direct dependency's name (GET to npm); each listed domain (RDAP); a TLS handshake to each listed host; a GET to each listed URL. Never a package that resolves to a private registry, a git URL, a tarball or a path, the project's own npm scope or a listed private scope, a cookie or an auth header. Loopback, private, link-local, CGNAT, metadata and other special-use addresses are refused after DNS resolution (IPv6 outside global unicast included), and the socket is checked before a byte is sent; redirects are not followed. \`--no-network\` sends nothing |
| every other verb | Nothing | Nothing. ffmpeg is limited to the \`file\` protocol, so a recording that is really a playlist can't open a network address |

The user-run setup steps that \`ow-tools doctor\` prints reach: Homebrew (packages, and the Chrome cask), huggingface.co (the Whisper model; the pyannote model with the user's token), PyPI and python-build-standalone via uv (the Python environment).

## Files it writes

| What | Where |
|---|---|
| \`transcript.json\`, \`transcript.md\` (0600) | The workstream folder the user names (refused unless git-ignored when inside a repository) |
| \`<name>.pdf\`, \`<name>.docx\`, \`<name>.pptx\`, \`<name>.xlsx\` (0600) | \`export/\` beside the Markdown or the sheet folder, or \`--out\` |
| \`<name>.export.json\` (0600, 1.1.0) | Beside the exports: what was exported from what, the SHA-256s, the tool version and the time |
| Screenshots \`<step-id>.png\` (0600, 1.1.0) | The \`shots/\` folder given with \`--out\` (refused unless git-ignored when inside a repository) |
| The capture profile (0700, 1.1.0) | \`$OW_TOOLS_HOME/capture/<workstream>/\`: the browser's profile, holding the test session the user signed in to (cookies encrypted with the keychain key). Its caches are removed before and after every run; after a production run its cookies and site storage are wiped too, on an interrupt or kill signal as well, and a run killed outright leaves \`.ow-tools-production-pending\` so the next run wipes first; \`--delete-profile\` removes it |
| The RDAP list cache (0600, 1.1.0) | \`$OW_TOOLS_HOME/rdap/dns.json\`, refreshed after 30 days |
| pip-audit's own cache (1.1.0, when it runs) | pip-audit's HTTP cache in the user's cache folder (pip-audit's choice, not ow-tools') |
| Temporary audio, model output, Word and PowerPoint parts | A private (0700) temp folder, removed when the run ends |

## Files

| File | SHA-256 |
|---|---|
${rows.join("\n")}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      /* missing counts as drift */
    }
    if (current !== text) {
      console.error("✗ plugins/ow-tools/SECURITY-MANIFEST.md is out of date; run: node scripts/gen-ow-tools-manifest.mjs");
      process.exit(1);
    }
    console.log("✓ ow-tools security manifest is current");
  } else {
    writeFileSync(OUT, text);
    console.log("wrote plugins/ow-tools/SECURITY-MANIFEST.md");
  }
}
