#!/usr/bin/env node
// sync-skill-bundles.mjs
//
// Keeps every skill's bundled `references/orchestrator.md` and
// `references/checkpoint-protocol.md` in sync with their canonical sources.
// Also bundles the checkpoint/telemetry runtimes with portable launchers.
//
// Sources of truth:
//   - skills/orchestrator.md                    (bundled verbatim)
//   - skills/oc-checkpoint-protocol/SKILL.md    (bundled with YAML frontmatter stripped)
//   - scripts/{checkpoint,telemetry}.mjs       (bundled verbatim in owning skill)
//
// Run:        node scripts/sync-skill-bundles.mjs
// CI check:   node scripts/sync-skill-bundles.mjs --check   (exit 1 if drift)

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = process.env.OPCHAIN_SKILLS_DIR ?? join(REPO_ROOT, 'skills');
const ORCHESTRATOR_SRC = join(SKILLS_DIR, 'orchestrator.md');
const PROTOCOL_SRC = join(SKILLS_DIR, 'oc-checkpoint-protocol', 'SKILL.md');
// The skill whose SKILL.md IS the protocol source — it must not bundle a copy of
// itself as references/checkpoint-protocol.md (it still gets orchestrator.md).
const PROTOCOL_SOURCE_SKILL = 'oc-checkpoint-protocol';

const checkMode = process.argv.includes('--check');

function stripFrontmatter(md) {
  if (!md.startsWith('---\n')) return md;
  const end = md.indexOf('\n---\n', 4);
  if (end === -1) return md;
  return md.slice(end + 5).replace(/^\n+/, '');
}

function listSkills() {
  return readdirSync(SKILLS_DIR)
    .filter((entry) => {
      const path = join(SKILLS_DIR, entry);
      try {
        return statSync(path).isDirectory();
      } catch {
        return false;
      }
    })
    .sort();
}

function syncTarget(targetPath, expected, label) {
  let actual = '';
  let missing = false;
  try {
    actual = readFileSync(targetPath, 'utf8');
  } catch {
    actual = null;
    missing = true;
  }
  if (actual === expected) return { changed: false };

  if (checkMode) {
    return { changed: true, drift: true, missing };
  }
  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, expected);
  return { changed: true, missing };
}

const orchestratorContent = readFileSync(ORCHESTRATOR_SRC, 'utf8');
const protocolContent = stripFrontmatter(readFileSync(PROTOCOL_SRC, 'utf8'));

const drift = [];
const updated = [];

// The release updater ships with its skill so /oc-update needs no bootstrap.
if (listSkills().includes('oc-update')) {
  const label = 'oc-update/scripts/update.mjs';
  const result = syncTarget(join(SKILLS_DIR, label), readFileSync(join(REPO_ROOT, 'scripts/update-opchain.mjs'), 'utf8'), label);
  if (result.drift) drift.push(label);
  else if (result.changed) updated.push(label);
}

// Keep the executable runtime canonical at repo level while distributing it
// with the skill. The launcher targets the consuming project, not this copy's
// installation directory (which may also be global or in a plugin cache).
function portableLauncher(runtime) {
  return `#!/usr/bin/env node
// Generated by scripts/sync-skill-bundles.mjs. Edit the generator, not this file.
import { execFileSync, spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

let root = process.env.OPCHAIN_ROOT;
if (!root) {
  try {
    root = execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: process.cwd(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    root = process.cwd();
  }
}
const result = spawnSync(process.execPath, [
  fileURLToPath(new URL('./${runtime}.runtime.mjs', import.meta.url)),
  ...process.argv.slice(2),
], { stdio: 'inherit', env: { ...process.env, OPCHAIN_ROOT: resolve(root) } });
if (result.error) console.error(result.error.message);
process.exit(result.status ?? 1);
`;
}

for (const [skill, runtime] of [
  ['oc-telemetry-ops', 'telemetry'],
  ['oc-checkpoint-protocol', 'checkpoint'],
]) {
  // Fixture trees may contain a subset of the catalog.
  if (!listSkills().includes(skill)) continue;
  for (const [filename, expected] of [
    [`${runtime}.runtime.mjs`, portableLauncher(runtime).replace(`./${runtime}.runtime.mjs`, `./runtime/scripts/${runtime}.mjs`)],
    [`${runtime}.mjs`, portableLauncher(runtime)],
  ]) {
    const label = `${skill}/scripts/${filename}`;
    const result = syncTarget(join(SKILLS_DIR, label), expected, label);
    if (result.drift) drift.push(`${label}${result.missing ? ' (missing)' : ''}`);
    else if (result.changed) updated.push(`${label}${result.missing ? ' (created)' : ''}`);
  }
}

// One declared runtime closure is distributed to each owning skill, so individual
// ZIP installs work without another skill or a hidden authoring checkout.
const runtimeManifest = JSON.parse(readFileSync(join(REPO_ROOT, 'scripts/runtime-manifest.json'), 'utf8'));
for (const owner of runtimeManifest.owners.filter(id => listSkills().includes(id))) {
  if (!checkMode) rmSync(join(SKILLS_DIR, owner, 'scripts/runtime'), { recursive: true, force: true });
  for (const file of runtimeManifest.files) {
    if (file.split('/').some(part => !part || part === '.' || part === '..')) throw new Error(`Unsafe runtime manifest path: ${file}`);
    const label = `${owner}/scripts/runtime/${file}`;
    const result = syncTarget(join(SKILLS_DIR, label), readFileSync(join(REPO_ROOT, file), 'utf8'), label);
    if (result.drift) drift.push(label);
    else if (result.changed) updated.push(label);
  }
  if (['oc-hindsight', 'oc-evolve'].includes(owner)) {
    const guide = `${owner}/references/runtime-contract.md`;
    const result = syncTarget(join(SKILLS_DIR, guide), readFileSync(join(REPO_ROOT, 'scripts/runtime/README.md'), 'utf8'), guide);
    if (result.drift) drift.push(guide);
    else if (result.changed) updated.push(guide);
  }
  const label = `${owner}/scripts/opchain.mjs`;
  const launcher = portableLauncher('opchain').replace('./opchain.runtime.mjs', './runtime/scripts/opchain.mjs');
  const result = syncTarget(join(SKILLS_DIR, label), launcher, label);
  if (result.drift) drift.push(label);
  else if (result.changed) updated.push(label);

}

// Every skill directory bundles the shared protocol files so the skill is
// self-contained once installed into ~/.claude/skills. `references/` is created
// if absent — a skill shipping without these files is the drift this guards against.
for (const skill of listSkills()) {
  const refsDir = join(SKILLS_DIR, skill, 'references');

  const targets = [
    {
      path: join(refsDir, 'orchestrator.md'),
      expected: orchestratorContent,
      label: `${skill}/references/orchestrator.md`,
    },
  ];
  // The protocol source skill must not bundle a copy of its own body.
  if (skill !== PROTOCOL_SOURCE_SKILL) {
    targets.push({
      path: join(refsDir, 'checkpoint-protocol.md'),
      expected: protocolContent,
      label: `${skill}/references/checkpoint-protocol.md`,
    });
  }

  for (const t of targets) {
    const result = syncTarget(t.path, t.expected, t.label);
    if (result.drift) drift.push(`${t.label}${result.missing ? ' (missing)' : ''}`);
    else if (result.changed) updated.push(`${t.label}${result.missing ? ' (created)' : ''}`);
  }
}

if (checkMode) {
  if (drift.length) {
    console.error('Bundled skill references are out of sync with source:');
    drift.forEach((d) => console.error(`  ${d}`));
    console.error('\nFix: npm run sync-bundles');
    process.exit(1);
  }
  console.log('All bundled skill references are in sync.');
  process.exit(0);
}

if (updated.length === 0) {
  console.log('All bundled skill references already in sync.');
} else {
  console.log(`Synced ${updated.length} bundled file(s):`);
  updated.forEach((u) => console.log(`  ${u}`));
}
